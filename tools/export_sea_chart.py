"""Write apple/OdysseyKit/.../SeaChartData.swift from the original disk's sea chart.

The sea is described twice in the original: the LC2 chart (20x20 cells of depth,
current direction and speed) and the SEA MAP picture, whose green land and orange
reefs are what the ship runs aground on (the DRAW collision count).  The picture's
compass rose is left out: nobody should run aground on that.

    python3 -I tools/export_sea_chart.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from odyssey import data  # noqa: E402
from odyssey.hires import Hires, WIDTH  # noqa: E402

GREEN, ORANGE = 3, 5
ROWS = 160                      # below that is the text window
OUT = os.path.join(ROOT, 'apple', 'OdysseyKit', 'Sources', 'OdysseyKit', 'SeaChartData.swift')


def main():
    h = Hires()
    with open(os.path.join(ROOT, 'odyssey', 'assets', 'seamap.hgr'), 'rb') as f:
        h.load(f.read())
    rows = []
    for y in range(ROWS):
        colours = h.render_row(y, range(6))
        row = ''
        for x in range(WIDTH):
            compass = 108 <= y < 160 and x < 56
            c = colours[x]
            row += '#' if c == GREEN and not compass else '%' if c == ORANGE and not compass else '.'
        rows.append(row)
    cells = data.SEA_MAP
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/export_sea_chart.py from the original disk: the LC2 sea chart\n')
        f.write('// and the SEA MAP picture. Do not edit.\n')
        f.write('enum SeaChartData {\n')
        f.write('    /// LC2: column major, index = col * 20 + row + 1 (0 unused). A cell is depth x 1000\n')
        f.write('    /// + current direction x 100 + current speed; 0 is land.\n')
        f.write('    static let cells: [Int] = [\n')
        for i in range(0, len(cells), 20):
            f.write('        ' + ', '.join(str(v) for v in cells[i:i + 20]) + ',\n')
        f.write('    ]\n\n')
        f.write("    /// The picture, row by row from the north: '#' land, '%' reef, '.' open sea.\n")
        f.write('    static let picture: [String] = [\n')
        for row in rows:
            f.write('        "' + row + '",\n')
        f.write('    ]\n}\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
