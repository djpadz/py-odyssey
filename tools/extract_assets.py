"""Extract binary assets and data tables from the original disk image into odyssey/.

Usage: python3 tools/extract_assets.py Odyssey_TheCompleatAdv.dsk
"""
import os, sys, pprint
sys.path.insert(0, os.path.dirname(__file__))
from dos33 import Disk
import vars as ivars

ROOT = os.path.join(os.path.dirname(__file__), '..', 'odyssey')


def files(disk):
    out = {}
    for name, ft, t, s, ln in disk.catalog():
        raw = disk.read_file(t, s)
        if ft & 0x7F == 4:
            addr = raw[0] | raw[1] << 8
            n = raw[2] | raw[3] << 8
            out[name] = (addr, raw[4:4 + n])
        else:
            n = raw[0] | raw[1] << 8
            out[name] = (None, raw[2:2 + n])
    return out


def main(path):
    f = files(Disk(path))
    adir = os.path.join(ROOT, 'assets')
    os.makedirs(adir, exist_ok=True)
    for name, out in [('ISLAND 1', 'island1.hgr'), ('ISLAND 2', 'island2.hgr'),
                      ('SEA MAP', 'seamap.hgr'), ('LOGO', 'logo.hgr')]:
        data = f[name][1]
        open(os.path.join(adir, out), 'wb').write(data + bytes(8192 - len(data)))
    setup_addr, setup = f['APVENTURE SETUP']
    assert setup_addr == 0x800
    open(os.path.join(adir, 'setup.bin'), 'wb').write(setup)
    # Shape table lives at $1AA4 (POKE 808,164: POKE 809,26 in HAIL).
    shp = setup[0x1AA4 - 0x800:]
    open(os.path.join(adir, 'shapes.bin'), 'wb').write(shp[:0x2000 - 0x1AA4])

    v = ivars.load_bytes(setup)
    # LC2 is BLOADed over the LC array (at $0C61) when the Sea part starts.
    lc2_addr, lc2 = f['LC2']
    sea = ivars.decode('LC', lc2[5:5 + 802])

    # Strings keep their original $81 (CTRL-A) padding: it is invisible when printed
    # but counts toward LEN(), and the game slices them at fixed widths.
    tables = {
        'ISLAND_MAP': v['LC'],
        'SEA_MAP': sea,
        'G1': v['G1$'], 'G2': v['G2$'], 'G3': v['G3$'],
        'MN': v['MN$'], 'T': v['T$'], 'O': v['O$'], 'DR': v['DR$'],
        'ITEM_WEIGHT': v['GW'][:50],
        'ITEM_PRICE': v['AP'][:50],
    }
    # Every variable as it stands in the BLOADed table (the starting state of a
    # new game, before HAIL rolls the characteristics).
    init = {}
    for name, val in v.items():
        key = name.replace('$', '_S')
        if key in ('QT', 'L') and isinstance(val, list) and len(val) > 1:
            key += 'A'
        if isinstance(val, list):
            init[key] = val if len(val) > 1 else val[0]
        else:
            init[key] = val
    init['D_S'] = '\x04'
    tables['INITIAL_VARS'] = init
    with open(os.path.join(ROOT, 'data.py'), 'w') as out:
        out.write('"""Game tables extracted from the original disk (generated by tools/extract_assets.py)."""\n\n')
        for k, val in tables.items():
            out.write(f'{k} = {pprint.pformat(val, width=100, compact=True)}\n\n')


if __name__ == '__main__':
    main(sys.argv[1])
